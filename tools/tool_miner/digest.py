#!/usr/bin/env python3
"""Turn a Claude Code transcript (JSONL) into a compact, readable digest.

The digest keeps what shows how the work went, which is what a tool idea
comes from:
  - everything you said (spoken requests, corrections, interruptions),
  - every tool call as one line (Bash commands in full, other tools by target),
  - which calls failed and the first line of the error,
  - a short slice of each assistant reply (enough to see what a correction was about).
Tool *outputs* are dropped, which is most of a transcript's bytes.

    python3 tools/tool_miner/digest.py <transcript.jsonl> [--from-line N]

Used as a library by mine.py.
"""
from __future__ import annotations

import json
import re
import sys
from collections import Counter
from datetime import datetime
from pathlib import Path

DEFAULT_LIMITS = {
    "user_chars": 2500,
    "assistant_chars": 280,
    "command_chars": 300,
    "error_chars": 240,
    "session_max_chars": 40000,
}

_REMINDER = re.compile(r"<system-reminder>.*?</system-reminder>", re.S)
_CMD_NAME = re.compile(r"<command-name>(.*?)</command-name>", re.S)
_CMD_ARGS = re.compile(r"<command-args>(.*?)</command-args>", re.S)
_LOCAL_STDOUT = re.compile(r"<local-command-std(out|err)>.*?</local-command-std(out|err)>", re.S)
_TAGS = re.compile(r"</?command-(message|name|args)>")
_WS = re.compile(r"[ \t]+")

INTERRUPTED = "[Request interrupted by user"
TOOL_REJECTED = "The user doesn't want to proceed with this tool use"


def _clip(text: str, n: int) -> str:
    text = text.strip()
    if len(text) <= n:
        return text
    return text[: n - 1].rstrip() + "…"


def _one_line(text: str) -> str:
    return _WS.sub(" ", text.replace("\n", " ⏎ ")).strip()


def _when(ts: str | None) -> datetime | None:
    if not ts:
        return None
    try:
        return datetime.fromisoformat(ts.replace("Z", "+00:00")).astimezone()
    except ValueError:
        return None


class _Paths:
    """Shorten absolute paths under the repo to repo-relative ones."""

    def __init__(self, roots: list[str]):
        self.roots = sorted({r.rstrip("/") + "/" for r in roots if r}, key=len, reverse=True)

    def __call__(self, s: str) -> str:
        for r in self.roots:
            s = s.replace(r, "")
        return s


def _user_text(content) -> tuple[str, bool]:
    """Return (text, is_slash_command) for a user message, '' if nothing human in it."""
    if isinstance(content, list):
        parts = []
        for c in content:
            if c.get("type") == "text":
                parts.append(c.get("text", ""))
            elif c.get("type") == "image":
                parts.append("[image]")
        content = "\n".join(parts)
    if not isinstance(content, str):
        return "", False
    text = _REMINDER.sub("", content)
    name = _CMD_NAME.search(text)
    if name:
        args = _CMD_ARGS.search(text)
        cmd = name.group(1).strip()
        if not cmd.startswith("/"):
            cmd = "/" + cmd
        return (cmd + (" " + args.group(1).strip() if args and args.group(1).strip() else "")), True
    text = _LOCAL_STDOUT.sub("", text)
    text = _TAGS.sub("", text).strip()
    if text.startswith("Caveat: The messages below were generated by the user"):
        return "", False
    return text, False


def _tool_target(name: str, inp: dict, short, limits) -> str:
    """One short description of what a tool call was aimed at."""
    if not isinstance(inp, dict):
        return ""
    if name == "Bash":
        return "`" + _clip(_one_line(short(inp.get("command", ""))), limits["command_chars"]) + "`"
    for key in ("file_path", "notebook_path", "path"):
        if key in inp and isinstance(inp[key], str):
            extra = ""
            if name == "Grep" and inp.get("pattern"):
                extra = f" /{_clip(inp['pattern'], 60)}/"
            return short(inp[key]) + extra
    if name in ("Grep", "Glob") and inp.get("pattern"):
        return _clip(str(inp["pattern"]), 80)
    if name in ("WebFetch",) and inp.get("url"):
        return _clip(inp["url"], 100)
    if name in ("WebSearch",) and inp.get("query"):
        return _clip(inp["query"], 100)
    if name in ("Task", "Agent") and (inp.get("description") or inp.get("subagent_type")):
        return _clip(f"{inp.get('subagent_type', '')}: {inp.get('description', '')}", 100)
    if name == "Skill" and inp.get("skill"):
        return inp["skill"]
    if name.startswith("Todo") or name.startswith("Task"):
        return ""
    # MCP and anything else: the first couple of short scalar args
    bits = []
    for k, v in inp.items():
        if isinstance(v, (str, int, float, bool)) and len(str(v)) <= 80:
            bits.append(f"{k}={short(str(v))}")
        if len(bits) == 2:
            break
    return _clip(", ".join(bits), 140)


def _tool_name(name: str) -> str:
    if name.startswith("mcp__"):
        parts = name.split("__", 2)
        if len(parts) == 3:
            return f"{parts[1]}:{parts[2]}"
    return name


def _result_text(block) -> str:
    c = block.get("content")
    if isinstance(c, list):
        c = "\n".join(x.get("text", "") for x in c if isinstance(x, dict))
    return c if isinstance(c, str) else ""


def read_entries(path: Path, from_line: int = 0) -> tuple[list[dict], int]:
    """Parse the JSONL from `from_line`; returns (entries, total_line_count)."""
    entries = []
    n = 0
    with open(path, encoding="utf-8", errors="replace") as fh:
        for n, line in enumerate(fh, start=1):
            if n <= from_line:
                continue
            line = line.strip()
            if not line:
                continue
            try:
                entries.append(json.loads(line))
            except json.JSONDecodeError:
                continue
    return entries, n


def session_meta(path: Path) -> dict:
    """Cheap scan for id, cwd, first/last timestamp, title. Reads the whole file once."""
    meta = {"session_id": path.stem, "cwd": None, "title": None, "first": None, "last": None, "lines": 0}
    with open(path, encoding="utf-8", errors="replace") as fh:
        for n, line in enumerate(fh, start=1):
            meta["lines"] = n
            try:
                d = json.loads(line)
            except json.JSONDecodeError:
                continue
            if d.get("cwd") and not meta["cwd"]:
                meta["cwd"] = d["cwd"]
            if d.get("sessionId"):
                meta["session_id"] = d["sessionId"]
            if d.get("type") in ("ai-title", "summary"):
                meta["title"] = d.get("aiTitle") or d.get("summary") or meta["title"]
            ts = d.get("timestamp")
            if ts:
                meta["first"] = meta["first"] or ts
                meta["last"] = ts
    return meta


def digest(path: Path, from_line: int = 0, repo_roots: list[str] | None = None,
           limits: dict | None = None) -> dict:
    """Digest one transcript. Returns {session_id, text, lines, user_turns, tool_calls, ...}."""
    lim = dict(DEFAULT_LIMITS)
    lim.update(limits or {})
    entries, total_lines = read_entries(path, from_line)
    short = _Paths(repo_roots or [])

    session_id = path.stem
    title = None
    cwd = None
    branch = None
    first_ts = last_ts = None
    for d in entries:
        session_id = d.get("sessionId", session_id)
        if d.get("type") in ("ai-title", "summary"):
            title = d.get("aiTitle") or d.get("summary") or title
        cwd = cwd or d.get("cwd")
        branch = d.get("gitBranch") or branch
        if d.get("timestamp") and d.get("type") in ("user", "assistant"):
            first_ts = first_ts or d["timestamp"]
            last_ts = d["timestamp"]
    if cwd:
        short.roots.append(cwd.rstrip("/") + "/")

    # tool_use_id -> (is_error, text)
    results: dict[str, tuple[bool, str]] = {}
    for d in entries:
        if d.get("type") != "user":
            continue
        content = (d.get("message") or {}).get("content")
        if isinstance(content, list):
            for c in content:
                if c.get("type") == "tool_result":
                    results[c.get("tool_use_id", "")] = (bool(c.get("is_error")), _result_text(c))

    lines: list[str] = []
    tool_counts: Counter = Counter()
    commands: Counter = Counter()
    edited: Counter = Counter()
    errors = interruptions = rejections = user_turns = 0
    pending: list[tuple[str, str, bool, str]] = []  # (tool, target, error, errtext) for grouping

    def flush():
        nonlocal pending
        i = 0
        while i < len(pending):
            name, target, err, errtext = pending[i]
            if err:
                lines.append(f"  · ERR {name} {target} → {errtext}".rstrip())
                i += 1
                continue
            j = i
            while j + 1 < len(pending) and pending[j + 1][0] == name and not pending[j + 1][2]:
                j += 1
            group = pending[i : j + 1]
            if len(group) == 1:
                lines.append(f"  · {name} {target}".rstrip())
            elif name == "Bash":
                k = i
                while k <= j:  # collapse identical consecutive commands only
                    m = k
                    while m + 1 <= j and pending[m + 1][1] == pending[k][1]:
                        m += 1
                    times = f" ×{m - k + 1}" if m > k else ""
                    lines.append(f"  · Bash {pending[k][1]}{times}")
                    k = m + 1
            else:
                targets = [t for _, t, _, _ in group if t]
                uniq = list(dict.fromkeys(targets))
                shown = ", ".join(uniq[:6]) + (f", +{len(uniq) - 6} more" if len(uniq) > 6 else "")
                lines.append(f"  · {name} ×{len(group)}: {shown}".rstrip(": "))
            i = j + 1
        pending = []

    for d in entries:
        t = d.get("type")
        if d.get("isSidechain"):
            continue
        msg = d.get("message") or {}
        if t == "user":
            if d.get("isMeta"):
                continue
            content = msg.get("content")
            if isinstance(content, list) and any(c.get("type") == "tool_result" for c in content):
                for c in content:
                    if c.get("type") == "tool_result" and TOOL_REJECTED in _result_text(c):
                        flush()
                        rejections += 1
                        lines.append("  !! user rejected that tool call")
                continue
            text, is_cmd = _user_text(content)
            if not text:
                continue
            flush()
            if text.startswith(INTERRUPTED):
                interruptions += 1
                lines.append("  !! interrupted by user")
                continue
            user_turns += 1
            label = "CMD" if is_cmd else f"U{user_turns}"
            lines.append("")
            lines.append(f"{label}: {_clip(short(text), lim['user_chars'])}")
        elif t == "assistant":
            for c in msg.get("content") or []:
                ct = c.get("type")
                if ct == "text" and c.get("text", "").strip():
                    flush()
                    lines.append(f"  A: {_clip(_one_line(short(c['text'])), lim['assistant_chars'])}")
                elif ct == "tool_use":
                    name = _tool_name(c.get("name", "?"))
                    inp = c.get("input") or {}
                    target = _tool_target(c.get("name", ""), inp, short, lim)
                    err, rtext = results.get(c.get("id", ""), (False, ""))
                    errtext = ""
                    if err:
                        errors += 1
                        first = next((l for l in rtext.splitlines() if l.strip()), "")
                        errtext = _clip(_one_line(short(first)), lim["error_chars"])
                    tool_counts[name] += 1
                    if name == "Bash":
                        commands[_clip(_one_line(short(inp.get("command", ""))), 120)] += 1
                    if name in ("Edit", "Write", "MultiEdit", "NotebookEdit"):
                        edited[target] += 1
                    pending.append((name, target, err, errtext))
    flush()

    t0, t1 = _when(first_ts), _when(last_ts)
    span = ""
    if t0 and t1:
        span = f"{t0:%Y-%m-%d %H:%M} → {t1:%H:%M} ({int((t1 - t0).total_seconds() // 60)} min)"
    head = f"### Session {session_id[:8]}"
    if title:
        head += f" — \"{title}\""
    if span:
        head += f" — {span}"
    if branch and branch != "HEAD":
        head += f", branch {branch}"
    if from_line:
        head += f"  (continued: new activity from transcript line {from_line + 1})"

    stats = [
        f"Stats: {user_turns} user turns, {sum(tool_counts.values())} tool calls, "
        f"{errors} failed calls, {interruptions} interruptions, {rejections} rejected tool calls",
    ]
    if tool_counts:
        stats.append("Tools: " + ", ".join(f"{k} {v}" for k, v in tool_counts.most_common(10)))
    repeated = [(c, n) for c, n in commands.most_common(8) if n > 1]
    if repeated:
        stats.append("Repeated commands: " + "; ".join(f"`{c}` ×{n}" for c, n in repeated))
    if edited:
        stats.append("Edited: " + ", ".join(f"{k} ×{v}" if v > 1 else k for k, v in edited.most_common(10)))

    body = "\n".join(lines).strip("\n")
    budget = lim["session_max_chars"] - sum(len(s) for s in stats) - len(head) - 200
    if len(body) > budget > 0:
        keep = budget // 2
        cut = body.count("\n", keep, len(body) - keep)
        body = body[:keep] + f"\n\n  [… {cut} lines omitted from the middle of this session …]\n\n" + body[-keep:]

    text = f"{head}\n\n{body}\n\n" + "\n".join(stats) + "\n"
    return {
        "session_id": session_id,
        "title": title,
        "cwd": cwd,
        "text": text,
        "lines": total_lines,
        "user_turns": user_turns,
        "tool_calls": sum(tool_counts.values()),
        "first": first_ts,
        "last": last_ts,
    }


def main(argv: list[str]) -> int:
    import argparse

    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("transcript", type=Path)
    ap.add_argument("--from-line", type=int, default=0)
    ap.add_argument("--root", action="append", default=[], help="path prefix to shorten (repeatable)")
    a = ap.parse_args(argv)
    d = digest(a.transcript, a.from_line, a.root)
    sys.stdout.write(d["text"])
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
